"""Exporta una copia SQLite a PostgreSQL sin regenerar ni modificar registros."""

import argparse
import json
import re
import sqlite3
from pathlib import Path


def identificador(nombre):
    return '"' + nombre.replace('"', '""') + '"'


def literal(valor, tipo=''):
    if valor is None:
        return 'NULL'
    if tipo.lower() == 'tinyint(1)':
        if valor not in (0, 1):
            raise ValueError('Un booleano SQLite tiene un valor distinto de 0 o 1')
        return 'TRUE' if valor else 'FALSE'
    if isinstance(valor, bytes):
        return "decode('" + valor.hex() + "', 'hex')"
    if isinstance(valor, (int, float)):
        return str(valor)
    if '\x00' in valor:
        raise ValueError('PostgreSQL no admite caracteres NUL en columnas de texto')
    return "'" + valor.replace("'", "''") + "'"


def tipo_postgres(tipo):
    tipo = tipo.lower()
    if tipo == 'tinyint(1)':
        return 'boolean'
    if 'int' in tipo:
        return 'bigint'
    if tipo in ('datetime', 'timestamp'):
        return 'timestamp(0) without time zone'
    if tipo in ('real', 'float', 'double'):
        return 'double precision'
    if tipo == 'blob':
        return 'bytea'
    if tipo.startswith(('varchar', 'char', 'text')) or not tipo:
        return 'text'
    raise ValueError('Tipo SQLite no soportado: ' + tipo)


def exportar(origen, destino, esquema):
    conexion = sqlite3.connect(origen.as_uri() + '?mode=ro', uri=True)
    if conexion.execute('PRAGMA integrity_check').fetchall() != [('ok',)]:
        raise ValueError('La copia de origen no pasó la comprobación de integridad')
    if conexion.execute('PRAGMA foreign_key_check').fetchall():
        raise ValueError('La copia de origen tiene referencias inválidas')
    tablas = conexion.execute("SELECT name, sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name").fetchall()
    sentencias = ['BEGIN;', 'SET standard_conforming_strings = on;', f'CREATE SCHEMA {identificador(esquema)};', f'SET LOCAL search_path TO {identificador(esquema)};']
    detalles = {}
    for nombre, creacion in tablas:
        columnas = conexion.execute(f'PRAGMA table_info({identificador(nombre)})').fetchall()
        primaria = [c[1] for c in sorted(columnas, key=lambda c: c[5]) if c[5]]
        autoincremento = 'AUTOINCREMENT' in creacion.upper()
        definiciones = []
        for _, columna, tipo, requerida, predeterminado, pk in columnas:
            definicion = identificador(columna) + ' ' + tipo_postgres(tipo)
            if pk and autoincremento:
                definicion += ' GENERATED BY DEFAULT AS IDENTITY'
            if requerida or pk:
                definicion += ' NOT NULL'
            if predeterminado is not None:
                valor = predeterminado.strip('()')
                if tipo.lower() == 'tinyint(1)':
                    valor = 'TRUE' if valor.strip("'") == '1' else 'FALSE'
                definicion += ' DEFAULT ' + valor
            definiciones.append(definicion)
        if primaria:
            definiciones.append('PRIMARY KEY (' + ', '.join(map(identificador, primaria)) + ')')
        sentencias.append(f'CREATE TABLE {identificador(nombre)} (' + ', '.join(definiciones) + ');')
        detalles[nombre] = (columnas, primaria, autoincremento)

    inventario = {}
    for nombre, _ in tablas:
        columnas, primaria, autoincremento = detalles[nombre]
        registros = conexion.execute(f'SELECT * FROM {identificador(nombre)}').fetchall()
        inventario[nombre] = len(registros)
        for inicio in range(0, len(registros), 100):
            valores = [ '(' + ', '.join(literal(v, columnas[i][2]) for i, v in enumerate(fila)) + ')' for fila in registros[inicio:inicio + 100] ]
            sentencias.append(f'INSERT INTO {identificador(nombre)} (' + ', '.join(identificador(c[1]) for c in columnas) + ') VALUES ' + ',\n'.join(valores) + ';')
        if autoincremento:
            secuencia = conexion.execute('SELECT seq FROM sqlite_sequence WHERE name=?', (nombre,)).fetchone()
            maximo = conexion.execute(f'SELECT max({identificador(primaria[0])}) FROM {identificador(nombre)}').fetchone()[0] or 0
            ultimo = max(maximo, secuencia[0] if secuencia else 0)
            sentencias.append(f"SELECT setval(pg_get_serial_sequence({literal(esquema + '.' + nombre)}, {literal(primaria[0])}), {max(1, ultimo)}, {'true' if ultimo else 'false'});")

    for nombre, _ in tablas:
        for _, indice, unico, procedencia, _ in conexion.execute(f'PRAGMA index_list({identificador(nombre)})'):
            if procedencia == 'pk':
                continue
            columnas = [fila[2] for fila in conexion.execute(f'PRAGMA index_info({identificador(indice)})')]
            if any(c is None for c in columnas):
                raise ValueError('Un índice de expresión requiere conversión manual')
            nombre_indice = indice if not indice.startswith('sqlite_') else nombre + '_' + '_'.join(columnas) + '_unique'
            sentencias.append('CREATE ' + ('UNIQUE ' if unico else '') + f'INDEX {identificador(nombre_indice)} ON {identificador(nombre)} (' + ', '.join(map(identificador, columnas)) + ');')
        claves = {}
        for numero, orden, referencia, desde, hacia, actualizar, borrar, _ in conexion.execute(f'PRAGMA foreign_key_list({identificador(nombre)})'):
            claves.setdefault(numero, []).append((orden, referencia, desde, hacia, actualizar, borrar))
        for numero, partes in claves.items():
            partes.sort()
            _, referencia, _, _, actualizar, borrar = partes[0]
            sentencias.append(f'ALTER TABLE {identificador(nombre)} ADD CONSTRAINT {identificador(nombre + "_fk_" + str(numero))} FOREIGN KEY (' + ', '.join(identificador(p[2]) for p in partes) + f') REFERENCES {identificador(referencia)} (' + ', '.join(identificador(p[3]) for p in partes) + f') ON UPDATE {actualizar} ON DELETE {borrar} DEFERRABLE INITIALLY IMMEDIATE;')
        sentencias.append(f'ALTER TABLE {identificador(nombre)} ENABLE ROW LEVEL SECURITY;')
    sentencias.append('COMMIT;')
    destino.parent.mkdir(parents=True, exist_ok=True)
    destino.write_text('\n'.join(sentencias) + '\n', encoding='utf-8')
    destino.chmod(0o600)
    destino.with_suffix('.inventario.json').write_text(json.dumps(inventario, indent=2), encoding='utf-8')
    print(f'Exportadas {len(tablas)} tablas y {sum(inventario.values())} registros a {destino}')


if __name__ == '__main__':
    argumentos = argparse.ArgumentParser(description=__doc__)
    argumentos.add_argument('origen', type=Path)
    argumentos.add_argument('destino', type=Path)
    argumentos.add_argument('--esquema', default='nexzone')
    opciones = argumentos.parse_args()
    if not re.fullmatch('[a-z][a-z0-9_]*', opciones.esquema):
        argumentos.error('Nombre de esquema inválido')
    exportar(opciones.origen.resolve(), opciones.destino.resolve(), opciones.esquema)
